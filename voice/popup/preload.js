const { contextBridge, ipcRenderer } = require("electron");

contextBridge.exposeInMainWorld("sunday", {
  servers: () => ipcRenderer.invoke("servers"),
  machine: () => ipcRenderer.invoke("machine"),
  uiState: () => ipcRenderer.invoke("ui-state"),
  ui: (state) => ipcRenderer.send("ui", state),
  place: (name, rect) => ipcRenderer.send("place", name, rect),
  pass: (on) => ipcRenderer.send("pass", on),
  detailsRect: (rect) => ipcRenderer.send("details-rect", rect),
  detailsClose: () => ipcRenderer.send("details-close"),
  settingsMenu: () => ipcRenderer.send("settings-menu"),
  onToggleMode: (fn) => ipcRenderer.on("toggle-mode", (_e, to) => fn(to)),
  onStatusFeed: (fn) => ipcRenderer.on("status-feed", (_e, feed) => fn(feed)),
  onComputerAudio: (fn) => ipcRenderer.on("computer-audio", (_e, playing) => fn(playing)),
  connection: (ok) => ipcRenderer.send("connection", ok),
  voice: (on) => ipcRenderer.send("voice", on),
  light: (on) => ipcRenderer.send("light", on),
  onToggleVoice: (fn) => ipcRenderer.on("toggle-voice", fn),
  overlay: (on, by) => ipcRenderer.send("overlay", on, by),
  onOverlayState: (fn) => ipcRenderer.on("overlay-state", (_e, state) => fn(state)),
  onNotice: (fn) => ipcRenderer.on("notice", (_e, text) => fn(text)),
  canvas: (payload, rect) => ipcRenderer.send("canvas", payload, rect),
  canvasClose: (id, by) => ipcRenderer.send("canvas-close", id, by),
  canvasReopen: (id, rect) => ipcRenderer.send("canvas-reopen", id, rect),
  canvasSpeaking: (state) => ipcRenderer.send("canvas-speaking", state),
  onCanvasOpen: (fn) => ipcRenderer.on("canvas-open", (_e, state) => fn(state)),
  onCanvasReport: (fn) => ipcRenderer.on("canvas-report", (_e, state) => fn(state)),
  onCanvasClosedHere: (fn) => ipcRenderer.on("canvas-closed-here", (_e, state) => fn(state)),
  isMac: process.platform === "darwin",
});
